#!/usr/bin/env python3
"""Reproduce pinned default case-fold data using the installed CPython UCD.
No network access. Refuse silent Unicode-version upgrades.
"""
import json
from pathlib import Path
import unicodedata

VERSION = "15.0.0"
if unicodedata.unidata_version != VERSION:
    raise SystemExit(f"requires Unicode {VERSION}; found {unicodedata.unidata_version}")
entries = {}
for point in range(0x110000):
    if 0xD800 <= point <= 0xDFFF:
        continue
    char = chr(point)
    folded = char.casefold()
    if folded != char:
        entries[str(point)] = folded
body = "// Generated by scripts/build-casefold.py; Unicode default full case folding.\n"
body += f'export const CASE_FOLD_UNICODE_VERSION = "{VERSION}";\n'
body += "export const CASE_FOLD: Readonly<Record<string, string>> = Object.freeze(\n"
body += json.dumps(entries, ensure_ascii=True, indent=2) + "\n);\n"
(Path(__file__).resolve().parent.parent / "src/core/casefold-data.ts").write_text(body, encoding="utf-8")
print(f"generated {len(entries)} mappings for Unicode {VERSION}")
